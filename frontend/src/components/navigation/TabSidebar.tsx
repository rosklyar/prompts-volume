export function TabSidebar({ activeTab, onTabChange }: TabSidebarProps) {
  const tabs = [
    { key: "dashboard" as const, label: "Dashboard", Icon: ChartIcon },
    { key: "prompts" as const, label: "Prompts", Icon: DocumentIcon },
    { key: "sources" as const, label: "Sources", Icon: LinkIcon },
    { key: "competitors" as const, label: "Competitors", Icon: CompetitorsIcon },
    { key: "geo-audit" as const, label: "GEO Audit", Icon: GeoAuditIcon },
  ]

  return (
    <nav className="flex flex-col gap-1">
      {tabs.map(({ key, label, Icon }) => {
        const isActive = activeTab === key
        return (
          <button
            key={key}
            onClick={() => onTabChange(key)}
            className={`flex items-center gap-3 px-4 py-2.5 rounded-lg transition-all duration-200
              ${isActive
                ? "bg-[#C4553D] text-white shadow-sm"
                : "text-[#6B7280] hover:bg-gray-100 hover:text-[#1F2937]"
              }`}
          >
            <Icon active={isActive} />
            <span
              className={`text-sm font-['DM_Sans'] font-medium transition-colors`}
            >
              {label}
            </span>
          </button>
        )
      })}
    </nav>
  )
}
